score = int(input("What's your Score: "))


if score >= 80 and score <=100:
    print("Grade: A+")

elif score >=70 and score <=80:
    print("Grade: B+")

elif score >= 60 and score <=70:
    print("Grade: C+")

elif score >= 50 and score <=60:
    print("Grade: D+")

else:
    print("Grade F", "Try hard, you can do it")

